// Interaction latency probe (Event Timing API) for common actions, CPU throttled 4x.
import { chromium, devices } from '@playwright/test';
import { sampleBackup } from '../../tests/e2e/sample-data.mjs';
const [, , mode = 'desktop', css = ''] = process.argv;
const base = 'http://localhost:3100';
const browser = await chromium.launch();
const ctx = await browser.newContext(mode === 'mobile' ? { ...devices['Pixel 7'] } : { viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
await page.goto(base + '/app');
await page.evaluate(() => localStorage.setItem('lifeos.identity', JSON.stringify({ mode: 'local' })));
await page.goto(base + '/app');
await page.getByRole('heading', { name: 'What do you want LIFEOS to help with?' }).waitFor();
for (const i of ['Work', 'Study', 'Money', 'Health', 'Home', 'Travel']) await page.locator('section').getByRole('button', { name: i, exact: true }).click();
await page.getByRole('button', { name: 'Continue' }).click();
await page.getByRole('button', { name: 'Continue' }).click();
await page.getByRole('button', { name: 'Start using LIFEOS' }).click();
await page.getByText(/Welcome to LIFEOS/).waitFor();
await page.goto(base + '/app/settings/data');
await page.getByLabel('Backup file').setInputFiles({ name: 'b.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(sampleBackup())) });
await page.getByRole('button', { name: 'Restore', exact: true }).click();
await page.getByText(/Restore complete/).waitFor();
await page.goto(base + '/app/tasks');
await page.waitForTimeout(2500);
if (css) await page.addStyleTag({ content: css });
const cdp = await ctx.newCDPSession(page);
await cdp.send('Emulation.setCPUThrottlingRate', { rate: 4 });
await page.evaluate(() => { window.__ev = []; new PerformanceObserver((l) => l.getEntries().forEach((e) => window.__ev.push({ n: e.name, d: e.duration, t: e.target?.getAttribute?.('aria-label') || e.target?.tagName }))).observe({ type: 'event', durationThreshold: 16, buffered: false }); });
const results = {};
async function act(name, fn) { await page.evaluate(() => (window.__ev = [])); await fn(); await page.waitForTimeout(700); results[name] = await page.evaluate(() => Math.round(Math.max(0, ...window.__ev.map((e) => e.d)))); }
await act('type quick-add', () => page.getByLabel('Quick add task').pressSequentially('Buy milk tomorrow', { delay: 40 }));
await act('submit quick-add', () => page.getByLabel('Quick add task').press('Enter'));
await act('toggle task', () => page.locator('#main-scroll .row').first().getByRole('checkbox').click());
await act('open editor', () => page.locator('#main-scroll').getByRole('button', { name: /^Write homepage/ }).click());
await act('type in editor', () => page.getByRole('dialog').getByLabel('Title').pressSequentially(' again', { delay: 40 }));
await act('close editor', () => page.keyboard.press('Escape'));
await act('switch to board', () => page.getByRole('tab', { name: /Board/ }).click());
await act('open palette', () => page.keyboard.press('Control+k'));
await act('type in palette', () => page.keyboard.type('pla', { delay: 50 }));
await act('close palette', () => page.keyboard.press('Escape'));
await act('nav home', () => (mode === 'mobile' ? page.getByRole('navigation', { name: 'Primary' }).getByRole('button', { name: 'Home' }) : page.getByRole('link', { name: 'Home' })).click());
console.log(mode, JSON.stringify(results));
await browser.close();
